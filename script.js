const languageToggle = document.querySelector("#language-toggle");
const themeToggle = document.querySelector("#theme-toggle");
const formContato = document.querySelector("#form-contato");
const formStatus = document.querySelector("#form-status");
let currentLanguage = "pt";
let currentTheme = localStorage.getItem("portfolio-theme");

if (currentTheme !== "light" && currentTheme !== "dark") {
    currentTheme = "dark";
}

function updateThemeControl() {
    const isLight = currentTheme === "light";
    const actionLabel = translations[currentLanguage][isLight ? "themeToDark" : "themeToLight"];

    themeToggle.innerHTML = `<i class="bi ${isLight ? "bi-moon-fill" : "bi-sun-fill"}" aria-hidden="true"></i>`;
    themeToggle.setAttribute("aria-label", actionLabel);
    themeToggle.title = actionLabel;
    themeToggle.setAttribute("aria-pressed", String(isLight));
}

function setTheme(theme) {
    currentTheme = theme;
    document.documentElement.dataset.theme = theme;
    localStorage.setItem("portfolio-theme", theme);
    updateThemeControl();
}

setTheme(currentTheme);

function setLanguage(language) {
    currentLanguage = language;
    const text = translations[language];

    document.documentElement.lang = language === "pt" ? "pt-BR" : "en";
    document.title = text[document.body.dataset.titleKey] || text.title;
    const description = document.querySelector('meta[name="description"]');
    description.content = text[description.dataset.i18nDescription] || text.description;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        element.textContent = text[element.dataset.i18n];
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        element.placeholder = text[element.dataset.i18nPlaceholder];
    });

    document.querySelectorAll("[data-i18n-value]").forEach((element) => {
        element.value = text[element.dataset.i18nValue];
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
        element.alt = text[element.dataset.i18nAlt];
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
        element.setAttribute("aria-label", text[element.dataset.i18nAria]);
    });

    languageToggle.textContent = language === "pt" ? "EN" : "PT";
    languageToggle.setAttribute("aria-label", text.switchLanguage);
    updateThemeControl();
}

languageToggle.addEventListener("click", () => {
    setLanguage(currentLanguage === "pt" ? "en" : "pt");
});

themeToggle.addEventListener("click", () => {
    setTheme(currentTheme === "dark" ? "light" : "dark");
});

if (formContato) {
    formContato.addEventListener("submit", (event) => {
    event.preventDefault();

    const text = translations[currentLanguage];
    const dados = new FormData(formContato);
    const nome = dados.get("nome").trim();
    const email = dados.get("email").trim();
    const celular = dados.get("celular").trim();
    const mensagem = dados.get("mensagem").trim();

    if (!nome || !email || !mensagem) {
        formStatus.textContent = text.requiredFields;
        formStatus.className = "form-status erro";
        return;
    }

    const assunto = encodeURIComponent(text.emailSubject(nome));
    const corpo = encodeURIComponent(
        `${text.emailName}: ${nome}\n` +
        `${text.emailAddress}: ${email}\n` +
        `${text.emailPhone}: ${celular || text.noPhone}\n\n` +
        `${text.emailMessage}:\n${mensagem}`
    );

    formStatus.textContent = text.openingEmail;
    formStatus.className = "form-status sucesso";

    const gmailUrl =
        `https://mail.google.com/mail/?view=cm&fs=1` +
        `&to=elitonassessoria@gmail.com` +
        `&su=${assunto}&body=${corpo}`;

    const janela = window.open(gmailUrl, "_blank");

    if (!janela) {
        formStatus.textContent = text.popupBlocked;
        formStatus.className = "form-status erro";
        return;
    }

    formContato.reset();
    formStatus.textContent = text.emailPrepared;
    formStatus.className = "form-status sucesso";
    });
}
